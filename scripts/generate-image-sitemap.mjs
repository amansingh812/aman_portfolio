/**
 * Generates public/sitemap-images.xml from the real content data files.
 *
 * WHY A GENERATOR AND NOT A HAND-EDITED FILE:
 * An image sitemap that lists images which do not exist is worse than no image
 * sitemap at all — Google fetches every entry and a wall of 404s is a quality
 * signal working against you. This script only emits an <image:image> when the
 * file is actually present on disk, so the sitemap can never drift ahead of
 * reality.
 *
 * RUN IT after adding or renaming any image:
 *   node scripts/generate-image-sitemap.mjs
 *
 * It is safe to run repeatedly — it rewrites the file from scratch every time.
 */

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const PUBLIC = path.join(ROOT, "public")
const ORIGIN = "https://buildfirstsite.com"

const { BLOG_POSTS } = await import("../content/blog.js")
const { LANDING_PAGES } = await import("../content/landing-pages.js")

/** True only if the referenced file really exists under /public. */
const exists = (webPath) =>
    Boolean(webPath) && fs.existsSync(path.join(PUBLIC, webPath.replace(/^\//, "")))

const esc = (s) =>
    String(s ?? "")
        .replace(/&/g, "&amp;")
        .replace(/</g, "&lt;")
        .replace(/>/g, "&gt;")
        .replace(/"/g, "&quot;")

/** entries: Map<pageUrl, [{loc, title, caption}]> — one <url> per page, always. */
const entries = new Map()
const add = (pageUrl, img) => {
    if (!entries.has(pageUrl)) entries.set(pageUrl, [])
    const list = entries.get(pageUrl)
    if (!list.some((i) => i.loc === img.loc)) list.push(img)
}

const skipped = []

/* ── Site-wide images that live outside the content files ── */
for (const [file, title, caption] of [
    ["/og-image.png", "Build First Site — web design and development studio",
        "Fixed-price websites for Australian small businesses"],
    ["/assets/imgs/og/default-og.png", "Build First Site",
        "Web design and development for Australian businesses"],
]) {
    if (exists(file)) add(`${ORIGIN}/`, { loc: ORIGIN + file, title, caption })
    else skipped.push(file)
}

/* ── Blog post card / hero images ── */
for (const post of BLOG_POSTS) {
    if (!post.image) continue
    if (!exists(post.image)) { skipped.push(`${post.image}  (blog: ${post.slug})`); continue }
    add(`${ORIGIN}/blog/${post.slug}/`, {
        loc: ORIGIN + post.image,
        title: post.metaTitle || post.title,
        caption: post.excerpt || post.metaDescription,
    })
}

/* ── Landing page hero images ── */
for (const page of LANDING_PAGES) {
    if (!page.image) continue
    if (!exists(page.image)) { skipped.push(`${page.image}  (landing: ${page.slug})`); continue }
    add(`${ORIGIN}/${page.slug}/`, {
        loc: ORIGIN + page.image,
        title: page.h1 || page.metaTitle,
        caption: page.imageAlt || page.metaDescription,
    })
}

/* ── In-body images inside blog post content ── */
try {
    const { BLOG_CONTENT } = await import("../content/blog-content.js")
    for (const [slug, post] of Object.entries(BLOG_CONTENT)) {
        for (const block of post.content || []) {
            if (block.type !== "image" || !block.src) continue
            if (!exists(block.src)) { skipped.push(`${block.src}  (in-body: ${slug})`); continue }
            add(`${ORIGIN}/blog/${slug}/`, {
                loc: ORIGIN + block.src,
                title: block.alt,
                caption: block.caption || block.alt,
            })
        }
    }
} catch {
    /* blog-content.js is optional for this script */
}

/* ── Emit ── */
const urls = [...entries.entries()]
    .map(([pageUrl, imgs]) => {
        const body = imgs
            .map(
                (i) =>
                    `    <image:image>\n` +
                    `      <image:loc>${esc(i.loc)}</image:loc>\n` +
                    `      <image:title>${esc(i.title)}</image:title>\n` +
                    (i.caption ? `      <image:caption>${esc(i.caption)}</image:caption>\n` : "") +
                    `    </image:image>`
            )
            .join("\n")
        return `  <url>\n    <loc>${esc(pageUrl)}</loc>\n${body}\n  </url>`
    })
    .join("\n\n")

const xml =
    `<?xml version="1.0" encoding="UTF-8"?>\n` +
    `<!-- GENERATED by scripts/generate-image-sitemap.mjs — do not edit by hand. -->\n` +
    `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"\n` +
    `        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">\n\n` +
    urls +
    `\n\n</urlset>\n`

fs.writeFileSync(path.join(PUBLIC, "sitemap-images.xml"), xml)

const total = [...entries.values()].reduce((n, l) => n + l.length, 0)
console.log(`sitemap-images.xml written — ${entries.size} pages, ${total} images`)

if (skipped.length) {
    console.log(`\n${skipped.length} referenced image(s) NOT on disk — omitted:`)
    for (const s of skipped) console.log("  -", s)
    console.log("\nGenerate these (see docs/IMAGE-SPEC-AUG-2026.md) then re-run this script.")
}
